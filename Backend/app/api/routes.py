"""
Minimal FastAPI app for AI Companion MVP
---------------------------------------
Exports a FastAPI `app` with a single endpoint that
accepts a `ChatRequest` and returns a `ChatResponse`
generated by the backend `AIService`.

Loads environment variables from `.env` if present.
"""

from typing import Optional
import logging
import os
from fastapi import FastAPI, status

from Backend.app.api.schemas import ChatRequest, ChatResponse


logger = logging.getLogger(__name__)

# Exported FastAPI application for root main.py to import
app = FastAPI(title="AI Companion MVP")

# Load environment variables from common locations
try:
	from dotenv import load_dotenv
	# Try repo root .env then Backend/.env
	load_dotenv(dotenv_path=os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(__file__))), ".env"), override=False)
	load_dotenv(dotenv_path=os.path.join(os.path.dirname(os.path.dirname(__file__)), ".env"), override=False)
except Exception:
	# If python-dotenv isn't available, continue; env can be set externally
	pass


@app.post("/chat", response_model=ChatResponse)
async def chat(request: ChatRequest) -> ChatResponse:
	"""
	Minimal chat endpoint:
	- Validates message is non-empty
	- Instantiates `AIService` with provided `ChatConfig`
	- Calls `send_message()` and returns `ChatResponse`
    
	Note: History is accepted but not used in this minimal MVP.
	"""
	if not request.message or not request.message.strip():
		return ChatResponse(
			status=status.HTTP_400_BAD_REQUEST,
			content=None,
			error="Message cannot be empty",
		)

	try:
		# Lazy import to avoid import-time failures when dependencies are missing
		try:
			from AI.ai_service import AIService
		except ModuleNotFoundError as e:
			if "google.generativeai" in str(e):
				logger.error("Missing dependency: google-genai. Install requirements.")
				return ChatResponse(
					status=status.HTTP_503_SERVICE_UNAVAILABLE,
					content=None,
					error="Missing dependency: google-genai. Install requirements.txt",
				)
			raise

		# Create per-request AI service using provided config
		service = AIService(config=request.config)

		# Minimal MVP: ignore history to keep implementation simple
		reply = service.send_message(request.message)

		return ChatResponse(
			status=status.HTTP_200_OK,
			content=reply,
			error=None,
		)

	except ValueError as e:
		# Configuration or validation error raised by AIService
		logger.warning(f"Validation error: {e}")
		return ChatResponse(
			status=status.HTTP_400_BAD_REQUEST,
			content=None,
			error=str(e),
		)
	except Exception as e:
		# Catch-all for provider or runtime errors
		logger.error(f"AI error: {e}")
		return ChatResponse(
			status=status.HTTP_503_SERVICE_UNAVAILABLE,
			content=None,
			error="AI service is unavailable",
		)

